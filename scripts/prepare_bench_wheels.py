"""Prepare the Linux CPython 3.12 Docker wheelhouse using the host network."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess
import sys
import venv
import zipfile

ROOT = Path(__file__).resolve().parents[1]
WHEELS = ROOT / "docker/bench/wheels"
REQUIREMENTS = ROOT / "docker/bench/requirements-wheels.txt"
CONSTRAINTS = ROOT / "docker/bench/constraints.txt"
TORCH = ["torch==2.8.0+cu128", "torchvision==0.23.0+cu128"]
TOOLS = ["pip", "uv>=0.8,<1", "setuptools==78.1.0", "wheel==0.48.0",
         "packaging==26.3", "ninja==1.13.2", "psutil==7.2.2", "py-cpuinfo==9.0.0", "hjson==3.1.0"]
EXTENSIONS = {
    "flash_attn": ("2.8.3.post2", "flash-attention"),
    "causal_conv1d": ("1.7.0", "causal-conv1d"),
}


def target_args() -> list[str]:
    # Ubuntu 22.04 has glibc 2.35. Do not accidentally select wheels requiring
    # the newer glibc of a host running Ubuntu 24.04 or another newer distro.
    args = ["--only-binary=:all:", "--python-version", "3.12",
            "--implementation", "cp", "--abi", "cp312"]
    for minor in range(35, 4, -1):
        args += ["--platform", f"manylinux_2_{minor}_x86_64"]
    for tag in ["manylinux2014_x86_64", "manylinux2010_x86_64", "manylinux1_x86_64", "linux_x86_64"]:
        args += ["--platform", tag]
    return args


def run(command: list[str], env: dict[str, str]) -> None:
    print("+", shlex.join(map(str, command)), flush=True)
    subprocess.run(command, cwd=ROOT, env=env, check=True)


def validate_wheel(path: Path) -> None:
    # A previous interrupted download must never be mistaken for a usable wheel.
    with zipfile.ZipFile(path) as archive:
        if not any(name.endswith(".dist-info/METADATA") for name in archive.namelist()):
            raise ValueError(f"No wheel metadata: {path}")
        bad_member = archive.testzip()
        if bad_member:
            raise ValueError(f"Corrupt wheel member {bad_member}: {path}")


def fetch_extension(name: str, version: str, repository: str,
                    override: str | None, env: dict[str, str]) -> Path:
    filename = f"{name}-{version}+cu12torch2.8cxx11abiTRUE-cp312-cp312-linux_x86_64.whl"
    destination = WHEELS / filename
    if destination.exists():
        validate_wheel(destination)
        print(f"Reusing {destination}", flush=True)
        return destination
    partial = destination.with_suffix(".whl.part")
    url = override or f"https://github.com/Dao-AILab/{repository}/releases/download/v{version}/{filename}"
    run(["curl", "--fail", "--location", "--retry", "5", "--connect-timeout", "30",
         "--max-time", "1800", "--output", str(partial), url], env)
    validate_wheel(partial)
    partial.replace(destination)
    return destination


def constraints_from_report(report: dict) -> str:
    selected: dict[str, str] = {}
    for item in report["install"]:
        metadata = item["metadata"]
        name = metadata["name"]
        version = metadata["version"]
        if name in selected and selected[name] != version:
            raise ValueError(f"Conflicting versions of {name}")
        selected[name] = version
    if not selected:
        raise ValueError("Empty dependency resolution report")
    return "# Generated by scripts/prepare_bench_wheels.py\n" + "".join(
        f"{name}=={selected[name]}\n" for name in sorted(selected, key=str.lower))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--index-url", default="https://pypi.org/simple")
    parser.add_argument("--torch-index-url", default="https://download.pytorch.org/whl/cu128")
    parser.add_argument("--flash-attn-wheel-url")
    parser.add_argument("--causal-conv1d-wheel-url")
    args = parser.parse_args()
    if sys.platform != "linux" or platform.machine() != "x86_64" or sys.version_info[:2] != (3, 12):
        parser.error("Run on the Linux x86_64 server with Python 3.12, not Windows or another Python version.")
    libc, libc_version = platform.libc_ver()
    if libc != "glibc" or tuple(map(int, libc_version.split(".")[:2])) < (2, 35):
        parser.error("The preparation environment needs glibc >= 2.35 (e.g. Ubuntu 22.04/24.04).")
    if not shutil.which("curl"):
        parser.error("curl is required")
    WHEELS.mkdir(parents=True, exist_ok=True)
    work = ROOT / ".venv-bench-wheels"
    if not (work / "bin/python").exists():
        venv.EnvBuilder(with_pip=True).create(work)
    python = str(work / "bin/python")
    env = os.environ.copy()
    # Make the selected indices explicit; do not inherit an earlier offline pip
    # setting or a constraint file from a different checkout/environment.
    for key in [key for key in env if key.startswith(("PIP_", "DS_BUILD_"))]:
        env.pop(key)
    env.pop("PYTHONPATH", None)
    env.update(PIP_CONFIG_FILE=os.devnull, PIP_DEFAULT_TIMEOUT="120", PIP_RETRIES="8",
               PIP_DISABLE_PIP_VERSION_CHECK="1", PYTHONNOUSERSITE="1", DS_BUILD_OPS="0")
    pip = [python, "-m", "pip"]
    run([python, "-c", "import sys; assert sys.version_info[:2] == (3, 12), 'Existing .venv-bench-wheels must use Python 3.12'"], env)
    run(pip + ["install", "--index-url", args.index_url, "--upgrade", "pip"], env)
    download = pip + ["download", "--dest", str(WHEELS)] + target_args()
    # First fetch the CUDA-specific packages without resolving ordinary packages
    # against the special PyTorch index. Resolve their full dependencies next.
    run(download + ["--no-deps", "--index-url", args.torch_index_url] + TORCH, env)
    run(download + ["--index-url", args.index_url, "--find-links", str(WHEELS),
                    "-c", str(CONSTRAINTS)] + TORCH + TOOLS, env)
    run(pip + ["install", "--no-index", "--find-links", str(WHEELS),
               "-c", str(CONSTRAINTS)] + TORCH + TOOLS, env)
    # DeepSpeed's sdist is converted to a wheel on the host, with all optional
    # native ops disabled. CPU selection avoids requiring a host CUDA toolkit;
    # this variable is NOT propagated into the runtime Docker image.
    build_env = dict(env, DS_ACCELERATOR="cpu")
    if not list(WHEELS.glob("deepspeed-0.19.7*-none-any.whl")):
        run(pip + ["wheel", "--no-deps", "--no-build-isolation", "--no-binary=deepspeed", "--index-url", args.index_url,
                   "--wheel-dir", str(WHEELS), "deepspeed==0.19.7"], build_env)
    deep_wheels = list(WHEELS.glob("deepspeed-0.19.7*-*.whl"))
    if not deep_wheels or any(not path.name.endswith("-none-any.whl") for path in deep_wheels):
        raise ValueError("Expected a pure Python DeepSpeed wheel with DS_BUILD_OPS=0")
    for path in deep_wheels:
        validate_wheel(path)
    extension_paths = [fetch_extension(name, version, repo,
                      args.flash_attn_wheel_url if name == "flash_attn" else args.causal_conv1d_wheel_url,
                      env) for name, (version, repo) in EXTENSIONS.items()]
    roots = ["-r", str(REQUIREMENTS)] + [str(path) for path in extension_paths]
    run(download + ["--index-url", args.index_url, "--find-links", str(WHEELS)] + roots, env)
    # --ignore-installed makes this a real closure check: the preparation venv
    # cannot conceal a missing transitive dependency in the wheel directory.
    report_path = WHEELS / "resolution.json"
    run(pip + ["install", "--dry-run", "--ignore-installed", "--no-index", "--find-links",
               str(WHEELS), "--report", str(report_path)] + target_args() + roots, env)
    report = json.loads(report_path.read_text(encoding="utf-8"))
    lock = WHEELS / "resolved-constraints.txt"
    lock.write_text(constraints_from_report(report), encoding="utf-8")
    wheels = sorted(WHEELS.glob("*.whl"))
    (WHEELS / "SHA256SUMS").write_text("".join(f"{sha256(path)}  {path.name}\n" for path in wheels), encoding="utf-8")
    print(f"Ready: {len(wheels)} wheel files in {WHEELS}")
    print("Offline dependency resolution passed; see explanation_here/08-Wheel预下载与离线安装.md")


if __name__ == "__main__":
    main()
